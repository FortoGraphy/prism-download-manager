/// Tool locations passed to yt-dlp.
#[derive(Clone, Debug, Default)]
pub struct ToolPaths {
    pub ytdlp: Option<PathBuf>,
    pub ffmpeg: Option<PathBuf>,
    pub ffprobe: Option<PathBuf>,
    pub deno: Option<PathBuf>,
}

/// Arguments shared by every yt-dlp call: ignore user config, tool locations, proxy, browser cookies.
pub fn global_args(tools: &ToolPaths, opts: &VideoOptions) -> Vec<String> {
    let mut a = vec!["--ignore-config".to_string()];
    if let Some(ff) = &tools.ffmpeg {
        // Pass the directory when ffprobe sits next to ffmpeg so yt-dlp finds both.
        let dir = ff.parent();
        let loc = match (&tools.ffprobe, dir) {
            (Some(fp), Some(d)) if fp.parent() == Some(d) => d.to_path_buf(),
            _ => ff.clone(),
        };
        a.push("--ffmpeg-location".into());
        a.push(loc.to_string_lossy().into_owned());
    }
    if let Some(deno) = &tools.deno {
        a.push("--js-runtimes".into());
        a.push(format!("deno:{}", deno.to_string_lossy()));
    }
    if let Some(p) = &opts.proxy {
        a.push("--proxy".into());
        a.push(p.clone());
    }
    if let Some(b) = &opts.cookies_from_browser {
        a.push("--cookies-from-browser".into());
        a.push(b.clone());
    }
    a
}

pub(crate) fn is_youtube(url: &str) -> bool {
    url::Url::parse(url)
        .ok()
        .and_then(|u| u.host_str().map(str::to_ascii_lowercase))
        .is_some_and(|h| {
            h == "youtu.be" || h.ends_with("youtube.com") || h.ends_with("youtube-nocookie.com")
        })
}

/// Request-context arguments. Cookies go through a Netscape file (see [`netscape_cookies`]).
/// The browser User-Agent is not forced on YouTube, where yt-dlp picks per-client UAs
/// that the returned stream URLs are bound to.
pub fn context_args(
    url: &str,
    ctx: &RequestContext,
    opts: &VideoOptions,
    cookie_file: Option<&Path>,
) -> Vec<String> {
    let mut a = Vec::new();
    if let Some(f) = cookie_file {
        a.push("--cookies".into());
        a.push(f.to_string_lossy().into_owned());
    }
    if let Some(r) = &ctx.referer {
        a.push("--add-headers".into());
        a.push(format!("Referer:{r}"));
    }
    if !is_youtube(url)
        && let Some(ua) = ctx.user_agent.as_ref().or(opts.user_agent.as_ref())
    {
        a.push("--add-headers".into());
        a.push(format!("User-Agent:{ua}"));
    }
    for (k, v) in &ctx.headers {
        if k.eq_ignore_ascii_case("cookie") {
            continue;
        }
        a.push("--add-headers".into());
        a.push(format!("{k}:{v}"));
    }
    a
}

/// Probe-specific arguments (`-J`, flat playlists).
pub fn probe_args(url: &str, ctx: &RequestContext) -> Vec<String> {
    vec![
        "-J".into(),
        "--no-warnings".into(),
        "--flat-playlist".into(),
        if ctx.want_playlist {
            "--yes-playlist".into()
        } else {
            "--no-playlist".into()
        },
        "--".into(),
        url.into(),
    ]
}

/// Build a Netscape cookies.txt for the page's site from a `Cookie` header value.
pub fn netscape_cookies(url: &str, cookie_header: &str, expires_unix: i64) -> Option<String> {
    let u = url::Url::parse(url).ok()?;
    let host = u.host_str()?.to_ascii_lowercase();
    let host = host.strip_prefix("www.").unwrap_or(&host);
    let domain = if host.parse::<std::net::IpAddr>().is_ok() {
        host.to_string()
    } else {
        format!(".{host}")
    };
    let include_sub = if domain.starts_with('.') {
        "TRUE"
    } else {
        "FALSE"
    };
    let mut out = String::from("# Netscape HTTP Cookie File\n# Generated by Prism\n\n");
    let mut n = 0;
    for pair in cookie_header.split(';') {
        let pair = pair.trim();
        let Some((name, value)) = pair.split_once('=') else {
            continue;
        };
        let name = name.trim();
        if name.is_empty() || name.contains(['\t', '\n']) || value.contains(['\t', '\n']) {
            continue;
        }
        out.push_str(&format!(
            "{domain}\t{include_sub}\t/\tFALSE\t{expires_unix}\t{name}\t{}\n",
            value.trim()
        ));
        n += 1;
    }
    (n > 0).then_some(out)
}

/// Temp file deleted on drop.
pub(crate) struct TempFile(pub PathBuf);

impl Drop for TempFile {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
    }
}

const COOKIE_PREFIX: &str = "prism-cookies-";

/// LinkedIn posts: yt-dlp reads the `<video data-sources>` of the public post page, which
/// LinkedIn renders for visitors without a session; a signed-in session gets the web app's page
/// without it. (LinkedIn Learning needs the session, so only posts.)
pub(crate) fn public_page_only(url: &str) -> bool {
    url::Url::parse(url).ok().is_some_and(|u| {
        u.host_str()
            .is_some_and(|h| h == "linkedin.com" || h.ends_with(".linkedin.com"))
            && (u.path().starts_with("/posts/") || u.path().starts_with("/feed/update/"))
    })
}

pub(crate) fn write_cookie_file(url: &str, ctx: &RequestContext) -> Result<Option<TempFile>> {
    let Some(cookies) = ctx.cookies.as_deref() else {
        return Ok(None);
    };
    if public_page_only(url) {
        return Ok(None);
    }
    let expires = chrono::Utc::now().timestamp() + 86_400;
    let Some(text) = netscape_cookies(url, cookies, expires) else {
        return Ok(None);
    };
    // The file holds the user's session cookies for the site. On Linux the temp dir is shared by
    // every account: create it new (nothing planted at that path is followed), owner-only (0600)
    // and under a random name, so no other account can read it or guess it.
    let mut file = tempfile::Builder::new()
        .prefix(COOKIE_PREFIX)
        .suffix(".txt")
        .tempfile()?;
    file.write_all(text.as_bytes())?;
    let (_, path) = file.keep().map_err(|e| e.error)?;
    Ok(Some(TempFile(path)))
}

/// Removes cookie files a crash left behind (they are deleted on drop otherwise). Only files of
/// this user can be removed, and only ones older than an hour, so a running job keeps its own.
pub(crate) fn sweep_stale_cookie_files() {
    let Ok(dir) = std::fs::read_dir(std::env::temp_dir()) else {
        return;
    };
    let hour_ago = std::time::SystemTime::now() - Duration::from_secs(3600);
    for e in dir.flatten() {
        let name = e.file_name();
        let name = name.to_string_lossy();
        if !(name.starts_with(COOKIE_PREFIX) && name.ends_with(".txt")) {
            continue;
        }
        let old = e
            .metadata()
            .and_then(|m| m.modified())
            .is_ok_and(|t| t < hour_ago);
        if old {
            let _ = std::fs::remove_file(e.path());
        }
    }
}

fn last_error(stderr: &str) -> String {
    let errs: Vec<&str> = stderr.lines().filter(|l| l.starts_with("ERROR:")).collect();
    if let Some(e) = errs.last() {
        return e.trim_start_matches("ERROR:").trim().to_string();
    }
    stderr
        .lines()
        .rev()
        .find(|l| !l.trim().is_empty())
        .unwrap_or("unknown error")
        .to_string()
}

pub(crate) async fn run_probe_json(ytdlp: &Path, args: Vec<String>) -> Result<String> {
    let out = process::run_capture(Tool::YtDlp, ytdlp, &args, Duration::from_secs(300)).await?;
    let stdout = String::from_utf8_lossy(&out.stdout);
    if !out.status.success() || stdout.trim().is_empty() {
        return Err(VideoError::ToolFailed {
            tool: Tool::YtDlp,
            code: out.status.code(),
            message: last_error(&String::from_utf8_lossy(&out.stderr)),
        });
    }
    // With `-J` the JSON is a single line; ignore any stray lines before it.
    let json = stdout
        .lines()
        .rev()
        .find(|l| l.trim_start().starts_with('{'))
        .unwrap_or(&stdout);
    Ok(json.to_string())
}

/// Extract `(_type, url)` for url-redirect results.
pub(crate) fn redirect_url(json: &str) -> Option<String> {
    let v: serde_json::Value = serde_json::from_str(json).ok()?;
    let t = v.get("_type")?.as_str()?;
    if t == "url" || t == "url_transparent" {
        return v.get("url")?.as_str().map(str::to_string);
    }
    None
}

/// Run a yt-dlp download job, streaming progress; returns the final file path.
pub(crate) async fn run_job(
    ytdlp: &Path,
    args: Vec<String>,
    progress: UnboundedSender<YtProgress>,
    cancel: CancellationToken,
) -> Result<PathBuf> {
    let mut cmd = process::command(ytdlp);
    cmd.args(&args);
    let mut sp = Spawned::spawn(&mut cmd)?;
    let stdout = sp.child.stdout.take().expect("piped");
    let stderr = sp.child.stderr.take().expect("piped");
    let (tx, mut rx) = mpsc::unbounded_channel::<String>();
    for reader in [
        Box::new(stdout) as Box<dyn tokio::io::AsyncRead + Unpin + Send>,
        Box::new(stderr),
    ] {
        let tx = tx.clone();
        tokio::spawn(async move {
            let mut r = tokio::io::BufReader::new(reader);
            let mut buf = Vec::new();
            loop {
                buf.clear();
                match r.read_until(b'\n', &mut buf).await {
                    Ok(0) | Err(_) => break,
                    Ok(_) => {
                        let line = String::from_utf8_lossy(&buf)
                            .trim_end_matches(['\r', '\n'])
                            .to_string();
                        if tx.send(line).is_err() {
                            break;
                        }
                    }
                }
            }
        });
    }
    drop(tx);

    let _ = progress.send(YtProgress {
        stage: Stage::Starting,
        ..Default::default()
    });
    let mut final_path: Option<String> = None;
    let mut errors: Vec<String> = Vec::new();
    let mut tail: Vec<String> = Vec::new();
    loop {
        tokio::select! {
            biased;
            _ = cancel.cancelled() => {
                sp.kill_tree().await;
                return Err(VideoError::Cancelled);
            }
            line = rx.recv() => {
                let Some(line) = line else { break };
                match parse_line(&line) {
                    Some(LineEvent::Progress(p)) => { let _ = progress.send(p); }
                    Some(LineEvent::FinalPath(p)) => final_path = Some(p),
                    Some(LineEvent::Error(e)) => errors.push(e),
                    Some(LineEvent::Warning(w)) => tracing::debug!("yt-dlp warning: {w}"),
                    None => {
                        if !line.trim().is_empty() {
                            tail.push(line);
                            if tail.len() > 20 { tail.remove(0); }
                        }
                    }
                }
            }
        }
    }
    let status = tokio::select! {
            biased;
        _ = cancel.cancelled() => {
            sp.kill_tree().await;
            return Err(VideoError::Cancelled);
        }
        st = sp.child.wait() => st?,
    };
    if !status.success() {
        let message = errors
            .last()
            .cloned()
            .or_else(|| tail.last().cloned())
            .unwrap_or_else(|| "unknown error".into());
        return Err(VideoError::ToolFailed {
            tool: Tool::YtDlp,
            code: status.code(),
            message,
        });
    }
    let path = final_path.map(PathBuf::from).ok_or_else(|| {
        VideoError::Other("yt-dlp finished but did not report the output file".into())
    })?;
    let _ = progress.send(YtProgress {
        stage: Stage::Finished,
        percent: Some(100.0),
        filename: Some(path.to_string_lossy().into_owned()),
        ..Default::default()
    });
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn linkedin_posts_are_read_without_the_session() {
        let ctx = RequestContext {
            cookies: Some("li_at=AQEDAR; JSESSIONID=ajax:1".into()),
            ..Default::default()
        };
        for url in [
            "https://www.linkedin.com/feed/update/urn:li:activity:7151241570371948544/",
            "https://www.linkedin.com/posts/the-mathworks_2_what-is-mathworks-cloud-center-activity-7151241570371948544-4Gu7",
        ] {
            assert!(public_page_only(url), "{url}");
            assert!(write_cookie_file(url, &ctx).unwrap().is_none(), "{url}");
        }
        // Everything else keeps the page's cookies (LinkedIn Learning needs them).
        for url in [
            "https://www.linkedin.com/learning/some-course/intro",
            "https://www.youtube.com/watch?v=aqz-KE-bpKQ",
            "https://notlinkedin.com/posts/x",
        ] {
            assert!(!public_page_only(url), "{url}");
        }
        let f =
            write_cookie_file("https://www.linkedin.com/learning/some-course/intro", &ctx).unwrap();
        assert!(f.is_some_and(|f| std::fs::read_to_string(&f.0).unwrap().contains("li_at")));
    }

    #[test]
    fn the_cookie_file_is_private_and_its_name_unguessable() {
        let ctx = RequestContext {
            cookies: Some("SID=secret".into()),
            ..Default::default()
        };
        let url = "https://www.youtube.com/watch?v=aqz-KE-bpKQ";
        let a = write_cookie_file(url, &ctx).unwrap().unwrap();
        let b = write_cookie_file(url, &ctx).unwrap().unwrap();
        assert_ne!(a.0, b.0);
        // It holds the user's session cookies: no other local account may read it...
        #[cfg(unix)]
        for f in [&a, &b] {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&f.0).unwrap().permissions().mode();
            assert_eq!(mode & 0o077, 0, "mode {mode:o}");
        }
        // ...nor predict the next name and plant a file or a link there first.
        let pid = std::process::id().to_string();
        for f in [&a, &b] {
            let name = f.0.file_name().unwrap().to_string_lossy().into_owned();
            assert!(
                name.starts_with(COOKIE_PREFIX) && name.ends_with(".txt") && !name.contains(&pid),
                "{name}"
            );
            assert!(
                std::fs::read_to_string(&f.0)
                    .unwrap()
                    .contains("SID	secret")
            );
        }
        // ...and it is gone when the job is done.
        let path = a.0.clone();
        drop(a);
        assert!(!path.exists());
    }
}
